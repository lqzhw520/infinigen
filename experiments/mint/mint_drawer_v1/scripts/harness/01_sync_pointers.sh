#!/bin/bash
# ============================================================
# 01_sync_pointers.sh
# Phase 1: Create/verify symlinks and stubs at root directory
# Run from: mint_drawer_v1/ root
# Usage: bash scripts/harness/01_sync_pointers.sh [--restore]
# ============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
CAMP_DIR_NAME="mint_drawer_v1"

# Verify we are in the right place
if [[ ! -d "$ROOT_DIR/sovereign" ]]; then
  echo "ERROR: sovereign/ not found at $ROOT_DIR/sovereign" >&2
  echo "This script must be run from within $CAMP_DIR_NAME/ root directory." >&2
  exit 1
fi

echo "=== Sync Pointers ==="
echo "Root: $ROOT_DIR"
echo ""

check_and_link() {
  local target="$1"   # relative to ROOT_DIR (e.g. sovereign/manifest.yaml)
  local link_name="$2"  # e.g. manifest.yaml

  local target_abs="$ROOT_DIR/$target"
  local link_abs="$ROOT_DIR/$link_name"

  if [[ ! -e "$target_abs" ]]; then
    echo "ERROR: target does not exist: $target_abs" >&2
    return 1
  fi

  if [[ -L "$link_abs" ]]; then
    local existing_target
    existing_target="$(readlink "$link_abs")"
    if [[ "$existing_target" == "$target" ]]; then
      echo "OK (already linked): $link_name -> $target"
    else
      echo "WARN: $link_name exists but points to $existing_target (expected $target). Replacing." >&2
      rm "$link_abs"
      ln -s "$target" "$link_abs"
      echo "RELINKED: $link_name -> $target"
    fi
  elif [[ -e "$link_abs" ]]; then
    echo "ERROR: $link_abs exists but is not a symlink. Will not overwrite." >&2
    return 1
  else
    ln -s "$target" "$link_abs"
    echo "LINKED: $link_name -> $target"
  fi
}

# Symlinks for YAML/JSON sovereign files
check_and_link "sovereign/manifest.yaml" "manifest.yaml"
check_and_link "sovereign/state.json" "state.json"
check_and_link "sovereign/next_actions.json" "next_actions.json"

# CAMPAIGN_TRUTH.md: TEXT STUB (not symlink) to prevent agent editing the target
CAMPAIGN_TRUTH_STUB="$ROOT_DIR/CAMPAIGN_TRUTH.md"
CAMPAIGN_TRUTH_TARGET="sovereign/CAMPAIGN_TRUTH.generated.md"
STUB_CONTENT="# CAMPAIGN_TRUTH (LEGACY POINTER)

DO NOT EDIT THIS FILE.
Canonical source: $CAMPAIGN_TRUTH_TARGET
This file was created by Harness v1.3 Phase 1.

If you see \"GENERATED FILE\" above, you have found the real truth.
"

if [[ -L "$CAMPAIGN_TRUTH_STUB" ]]; then
  rm "$CAMPAIGN_TRUTH_STUB"
fi

if [[ -f "$CAMPAIGN_TRUTH_STUB" ]]; then
  if grep -q "LEGACY POINTER" "$CAMPAIGN_TRUTH_STUB" 2>/dev/null; then
    echo "OK (stub exists): CAMPAIGN_TRUTH.md already has LEGACY POINTER text"
  else
    echo "WARN: CAMPAIGN_TRUTH.md exists with non-stub content. Replacing with pointer." >&2
    echo "$STUB_CONTENT" > "$CAMPAIGN_TRUTH_STUB"
    echo "REPLACED: CAMPAIGN_TRUTH.md with LEGACY POINTER stub"
  fi
else
  echo "$STUB_CONTENT" > "$CAMPAIGN_TRUTH_STUB"
  echo "CREATED: CAMPAIGN_TRUTH.md LEGACY POINTER stub"
fi

echo ""
echo "=== Pointer sync complete ==="
ls -la "$ROOT_DIR"/manifest.yaml "$ROOT_DIR"/state.json "$ROOT_DIR"/next_actions.json "$ROOT_DIR"/CAMPAIGN_TRUTH.md 2>/dev/null || true
